import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import mongoose from 'mongoose';
import request from 'supertest';
import {createApp} from '../src/app.js';
import {User} from '../src/features/users/user.model.js';
import {issueToken} from '../src/features/auth/tokens.js';
import {initializeBusiness, AdvanceModel, PaymentModel, Payroll, Audit} from '../src/domain/models.js';
import {monday, shift, today} from '../src/domain/values.js';

const uri = process.env.STAR_BUILDERS_TEST_MONGODB_URI;
test('real replica set: scoped attendance, immutable approval, recovery and concurrent oldest-first payments', {skip: !uri}, async () => {
    const dbName = `star_builders_business_test_${process.pid}_${Date.now()}`;
    await mongoose.connect(uri!, {dbName, serverSelectionTimeoutMS: 5000});
    try {
        await User.createIndexes();
        await initializeBusiness();
        const secret = 'business-integration-only-secret-32-chars';
        const admin = await User.create({name:'Test Admin', phone:'0000000001', role:'ADMIN', passwordHash:'unused-in-token-test'});
        const supervisor = await User.create({name:'Test Supervisor', phone:'0000000002', role:'SUPERVISOR', passwordHash:'unused-in-token-test'});
        const app = createApp({CORS_ORIGINS:['http://localhost:5173'], JWT_SECRET:secret}, async()=>true);
        const auth = `Bearer ${issueToken(admin.id, secret)}`;
        const limited = `Bearer ${issueToken(supervisor.id, secret)}`;
        const post = (path:string, body:unknown, token=auth) => request(app).post('/api'+path).set('Authorization',token).send(body);
        const get = (path:string, token=auth) => request(app).get('/api'+path).set('Authorization',token);
        const week = shift(monday(today()), -21), next = shift(week,7), third = shift(week,14);
        const first = (await post('/sites',{name:'Site One', budget:'10000.25',supervisorId:supervisor.id}).expect(201)).body.data;
        const second = (await post('/sites',{name:'Site Two'}).expect(201)).body.data;
        const visible = (await get('/sites',limited).expect(200)).body.data;
        assert.deepEqual(visible.map((site:{id:string})=>site.id),[first.id]);
        assert.equal(visible[0].budget,undefined);
        await post('/sites',{name:'Forbidden'},limited).expect(403);
        const worker = (await post('/labourers',{name:'Test Worker',category:'Mason',phone:'000001',rate:'850.00',from:week}).expect(201)).body.data;
        const privateWorker=(await get('/labourers',limited).expect(200)).body.data[0];
        assert.equal(privateWorker.phone,undefined);assert.equal(privateWorker.salaryHistory,undefined);assert.equal(privateWorker.rate,undefined);
        const attendance=(date:string,siteId=first.id,units=.5,ot='0')=>({labourId:worker.id,siteId,date,units,ot});
        await post('/attendance',attendance(week,second.id),limited).expect(403);
        await post('/attendance',attendance(week,first.id,.5,'.5'),limited).expect(200);
        await post('/attendance',attendance(week,second.id,.5)).expect(200);
        await post('/attendance',attendance(week,second.id,1)).expect(409);
        // Replacing a site's allocation must not duplicate it.
        await post('/attendance',{...attendance(week,first.id.toUpperCase(),.5,'.5'),labourId:worker.id.toUpperCase()}).expect(200);
        const adminRows=(await get('/attendance?date='+week).expect(200)).body.data;
        assert.equal(adminRows.length,2);assert.equal(adminRows.find((row:{siteId:string})=>row.siteId===first.id).earned,'478.13');
        const scopedRows=(await get('/attendance?date='+week,limited).expect(200)).body.data;
        assert.equal(scopedRows.length,1);assert.equal(scopedRows[0].earned,undefined);assert.equal(scopedRows[0].rate,undefined);
        const concurrentDate=shift(week,1);
        const concurrent=await Promise.all([post('/attendance',attendance(concurrentDate,first.id,1)),post('/attendance',attendance(concurrentDate,second.id,1))]);
        assert.deepEqual(concurrent.map(result=>result.status).sort(),[200,409]);
        await post('/attendance',attendance(shift(today(),1))).expect(400);
        await post('/labourers/'+worker.id+'/rates',{from:shift(week,3),rate:'900.00'}).expect(200);
        await post('/labourers/'+worker.id+'/rates',{from:shift(week,3),rate:'950.00'}).expect(409);
        // An explicit zero day exists; missing days create no rows. Sunday is ordinary rate.
        await post('/attendance',attendance(shift(week,2),first.id,0)).expect(200);
        await post('/attendance',attendance(shift(week,6),first.id,1)).expect(200);
        await post('/attendance',attendance(next,first.id,1)).expect(200);
        await post('/attendance',attendance(third,first.id,1)).expect(200);
        const advanceKey=randomUUID();
        const advance={labourId:worker.id,date:week,amount:'3000.00',requestId:advanceKey};
        const issued=await post('/advances',advance).expect(201);
        const replay=await post('/advances',advance).expect(201);
        assert.equal(issued.body.data.id,replay.body.data.id);assert.equal(await AdvanceModel.countDocuments(),1);
        await post('/advances',{...advance,amount:'3001.00'}).expect(409);
        const approval=(week:string)=>post('/payroll/approve',{week,requestId:randomUUID()});
        await approval(next).expect(409);
        const before=(await get('/payroll?week='+week).expect(200)).body.data.rows[0];
        assert.equal(before.gross,'2653.13');assert.equal(before.days,3);assert.equal(before.advance,'2653.13');assert.equal(before.net,'0.00');
        await approval(week).expect(200);
        assert.equal((await AdvanceModel.findOne())!.remainingPaise,34687);
        await post('/attendance',attendance(week,first.id,0)).expect(409);
        await post('/labourers/'+worker.id+'/rates',{from:shift(week,5),rate:'999.00'}).expect(409);
        const snapshot=(await Payroll.findOne({week}))!.toObject();
        await approval(week).expect(200);
        assert.equal(await Payroll.countDocuments({week}),1);
        await approval(next).expect(200);
        assert.equal((await AdvanceModel.findOne())!.remainingPaise,0);
        const nextRow=(await get('/payroll?week='+next).expect(200)).body.data.rows[0];
        assert.equal(nextRow.advance,'346.87');assert.equal(nextRow.net,'553.13');
        await approval(third).expect(200);
        const thirdRow=(await get('/payroll?week='+third).expect(200)).body.data.rows[0];
        assert.equal(thirdRow.broughtForward,'553.13');assert.equal(thirdRow.totalOutstanding,'1453.13');
        const payment={labourId:worker.id,throughWeek:third,date:today(),amount:'600.00',mode:'UPI',requestId:randomUUID()};
        const receipts=await Promise.all([post('/payments',payment),post('/payments',payment)]);
        assert.deepEqual(receipts.map(result=>result.status),[201,201]);assert.equal(receipts[0].body.data.id,receipts[1].body.data.id);
        assert.equal(await PaymentModel.countDocuments(),1);
        const ledger=(await PaymentModel.findOne())!;
        assert.deepEqual(ledger.allocations.map(allocation=>[allocation.week,allocation.amountPaise]),[[next,55313],[third,4687]]);
        await post('/payments',{...payment,amount:'601.00'}).expect(409);
        await post('/payments',{...payment,amount:'900.00',requestId:randomUUID()}).expect(409);
        const raced=await Promise.all([post('/payments',{...payment,amount:'500.00',requestId:randomUUID()}),post('/payments',{...payment,amount:'500.00',requestId:randomUUID()})]);
        assert.deepEqual(raced.map(result=>result.status).sort(),[201,409]);
        const remaining=(await get('/payroll?week='+third).expect(200)).body.data.rows[0];
        assert.equal(remaining.broughtForward,'0.00');assert.equal(remaining.balance,'353.13');
        assert.equal(remaining.history.reduce((sum:number,item:{amount:string})=>sum+Math.round(Number(item.amount)*100),0),54687);
        const after=(await Payroll.findOne({week}))!.toObject();
        assert.deepEqual(after.items,snapshot.items);assert.equal(after.grossPaise,snapshot.grossPaise);
        await get('/payroll?week='+week,limited).expect(403);
        await get('/reports/payments.csv',limited).expect(403);
        const csv=await get('/reports/salary.csv').expect(200);
        assert.match(csv.headers['content-type'],/text\/csv/);assert.match(csv.text,/2653.13/);
        assert.ok(await Audit.countDocuments({action:'SALARY_PAID'})===2);
        // Reassignment immediately removes site access, including writes to old dates.
        await request(app).patch('/api/sites/'+first.id+'/supervisor').set('Authorization',auth).send({supervisorId:null}).expect(200);
        assert.equal((await get('/sites',limited).expect(200)).body.data.length,0);
        await post('/attendance',attendance(shift(third,1)),limited).expect(403);
    } finally {
        assert.equal(mongoose.connection.name,dbName);
        await mongoose.connection.dropDatabase();
        await mongoose.disconnect();
    }
});
