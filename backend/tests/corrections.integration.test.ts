import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import mongoose from 'mongoose';
import request from 'supertest';
import {createApp} from '../src/app.js';
import {User} from '../src/features/users/user.model.js';
import {issueToken} from '../src/features/auth/tokens.js';
import {initializeBusiness, AdvanceModel, PaymentModel, Payroll, Adjustment, Reversal, LabourModel, Audit} from '../src/domain/models.js';
import {monday, shift, today} from '../src/domain/values.js';

const uri = process.env.STAR_BUILDERS_TEST_MONGODB_URI;
test('real replica set: audited corrections, recovered advance refunds and atomic payment reversals', {skip: !uri}, async()=>{
    const dbName=`star_builders_corrections_${process.pid}_${Date.now()}`;
    await mongoose.connect(uri!, {dbName, serverSelectionTimeoutMS:5000});
    try {
        await User.createIndexes();await initializeBusiness();
        const admin=await User.create({name:'Test Admin',phone:'000001',role:'ADMIN',passwordHash:'not-a-login-test'});
        const supervisor=await User.create({name:'Test Supervisor',phone:'000002',role:'SUPERVISOR',passwordHash:'not-a-login-test'});
        const secret='correction-tests-only-secret-32-characters';
        const app=createApp({CORS_ORIGINS:[],JWT_SECRET:secret},async()=>true);
        const auth=`Bearer ${issueToken(admin.id,secret)}`, limited=`Bearer ${issueToken(supervisor.id,secret)}`;
        const post=(path:string,body:unknown,token=auth)=>request(app).post('/api'+path).set('Authorization',token).send(body);
        const get=(path:string,token=auth)=>request(app).get('/api'+path).set('Authorization',token);
        const week=shift(monday(today()),-21), next=shift(week,7), third=shift(next,7);
        const site=(await post('/sites',{name:'Original Work Site'}).expect(201)).body.data;
        const worker=(await post('/labourers',{name:'Advance Worker',category:'Mason',rate:'1000.00',from:week}).expect(201)).body.data;
        const other=(await post('/labourers',{name:'Paid Worker',category:'Helper',rate:'1000.00',from:week}).expect(201)).body.data;
        for (const labourId of [worker.id,other.id]) await post('/attendance',{labourId,siteId:site.id,date:week,units:1,ot:'0'}).expect(200);
        const originalAdvance=(await post('/advances',{labourId:worker.id,date:week,amount:'1200.00',requestId:randomUUID()}).expect(201)).body.data.id;
        const approve=(week:string)=>post('/payroll/approve',{week,requestId:randomUUID()});
        await approve(week).expect(200);
        const original=(await Payroll.findOne({week,labourId:worker.id}))!.toObject();
        assert.equal(original.advancePaise,100000);assert.equal(original.netPaise,0);
        const reversal={date:today(),reason:'Duplicate advance entry',requestId:randomUUID()};
        await post('/advances/'+originalAdvance+'/reverse',reversal,limited).expect(403);
        await post('/advances/'+originalAdvance+'/reverse',{...reversal,reason:''}).expect(400);
        await post('/advances/'+originalAdvance+'/reverse',{...reversal,date:shift(week,-1)}).expect(400);
        const reverseResults=await Promise.all([post('/advances/'+originalAdvance.toUpperCase()+'/reverse',reversal),post('/advances/'+originalAdvance+'/reverse',reversal)]);
        assert.deepEqual(reverseResults.map(result=>result.status),[201,201]);
        assert.equal(reverseResults[0].body.data.id,reverseResults[1].body.data.id);
        assert.equal(reverseResults[0].body.data.refund,'1000.00');assert.equal(reverseResults[0].body.data.settlementWeek,next);
        await post('/advances/'+originalAdvance+'/reverse',{...reversal,requestId:randomUUID()}).expect(409);
        assert.equal(await Adjustment.countDocuments({kind:'ADVANCE_REFUND'}),1);
        // Advance counters and approved recovery snapshots retain their historical values.
        assert.equal((await AdvanceModel.findById(originalAdvance))!.remainingPaise,20000);
        const register=(await get('/advances').expect(200)).body.data.find((row:{id:string})=>row.id===originalAdvance);
        assert.equal(register.status,'Reversed');assert.equal(register.remaining,'0.00');assert.equal(register.recovered,'1000.00');
        const unused=(await post('/advances',{labourId:worker.id,date:next,amount:'50.00',requestId:randomUUID()}).expect(201)).body.data.id;
        await post('/advances/'+unused+'/reverse',{...reversal,requestId:randomUUID()}).expect(201);
        assert.equal(await Adjustment.countDocuments({kind:'ADVANCE_REFUND'}),1);
        const active=(await post('/advances',{labourId:worker.id,date:next,amount:'5000.00',requestId:randomUUID()}).expect(201)).body.data.id;
        const correction={labourId:worker.id,originalWeek:week,originalDate:week,siteId:site.id,direction:'Credit',amount:'200.00',reason:'Missed overtime',requestId:randomUUID()};
        await post('/payroll/adjustments',correction,limited).expect(403);
        await post('/payroll/adjustments',{...correction,originalDate:next}).expect(400);
        const created=await post('/payroll/adjustments',correction).expect(201);
        const replay=await post('/payroll/adjustments',correction).expect(201);
        assert.equal(created.body.data.id,replay.body.data.id);assert.equal(created.body.data.settlementWeek,next);
        await post('/payroll/adjustments',{...correction,amount:'201.00'}).expect(409);
        await post('/payroll/adjustments',{...correction,direction:'Debit',amount:'1200.01',requestId:randomUUID()}).expect(409);
        await post('/payroll/adjustments',{...correction,direction:'Debit',amount:'50.25',reason:'Excess salary correction',requestId:randomUUID()}).expect(201);
        for (const labourId of [worker.id,other.id]) await post('/attendance',{labourId,siteId:site.id,date:next,units:1,ot:'0'}).expect(200);
        const draft=(await get('/payroll?week='+next).expect(200)).body.data.rows.find((row:{id:string})=>row.id===worker.id);
        assert.equal(draft.adjustment,'1149.75');assert.equal(draft.advance,'1149.75');assert.equal(draft.net,'1000.00');
        await approve(third).expect(409);
        await approve(next).expect(200);
        assert.equal((await AdvanceModel.findById(active))!.remainingPaise,385025);
        assert.equal((await AdvanceModel.findById(originalAdvance))!.remainingPaise,20000);
        const unchanged=(await Payroll.findOne({week,labourId:worker.id}))!.toObject();
        assert.deepEqual(unchanged.items,original.items);assert.deepEqual(unchanged.recoveries,original.recoveries);assert.equal(unchanged.netPaise,original.netPaise);
        // Correction-only weeks include inactive workers and cannot approve a negative net.
        await LabourModel.updateOne({_id:worker.id},{$set:{status:'Inactive'}});
        await post('/payroll/adjustments',{...correction,direction:'Debit',amount:'.25',reason:'Quarter rupee excess',requestId:randomUUID()}).expect(201);
        const negative=(await get('/payroll?week='+third).expect(200)).body.data.rows.find((row:{id:string})=>row.id===worker.id);
        assert.equal(negative.net,'-0.25');assert.equal(negative.adjustment,'-0.25');
        await approve(third).expect(409);assert.equal(await Payroll.countDocuments({week:third}),0);
        await post('/payroll/adjustments',{...correction,amount:'.50',reason:'Offset earlier correction',requestId:randomUUID()}).expect(201);
        await approve(third).expect(200);
        assert.equal((await Payroll.findOne({week:third,labourId:worker.id}))!.adjustments.length,2);
        // A payment spanning original weeks is reversed once, restoring each allocation.
        const payment=(await post('/payments',{labourId:other.id,throughWeek:next,date:today(),amount:'1500.00',mode:'Cash',requestId:randomUUID()}).expect(201)).body.data;
        const paymentSnapshot=(await PaymentModel.findById(payment.id))!.toObject();
        const undo={date:today(),reason:'Incorrect payment entry',requestId:randomUUID()};
        // A mismatch after one allocation update rolls back the entire reversal.
        await Payroll.updateOne({week:next,labourId:other.id},{$set:{paidPaise:0}});
        await post('/payments/'+payment.id+'/reverse',undo).expect(409);
        assert.equal((await Payroll.findOne({week,labourId:other.id}))!.paidPaise,100000);
        assert.equal(await Reversal.countDocuments({sourceId:payment.id}),0);
        await Payroll.updateOne({week:next,labourId:other.id},{$set:{paidPaise:50000}});
        await post('/payments/'+payment.id+'/reverse',undo,limited).expect(403);
        const reversals=await Promise.all([post('/payments/'+payment.id+'/reverse',undo),post('/payments/'+payment.id+'/reverse',undo)]);
        assert.deepEqual(reversals.map(result=>result.status),[201,201]);assert.equal(reversals[0].body.data.id,reversals[1].body.data.id);
        await post('/payments/'+payment.id+'/reverse',{...undo,reason:'Different reason'}).expect(409);
        await post('/payments/'+payment.id+'/reverse',{...undo,requestId:randomUUID()}).expect(409);
        assert.deepEqual((await PaymentModel.findById(payment.id))!.toObject(),paymentSnapshot);
        assert.equal((await Payroll.findOne({week,labourId:other.id}))!.paidPaise,0);
        assert.equal((await Payroll.findOne({week:next,labourId:other.id}))!.paidPaise,0);
        const history=(await get('/payroll?week='+week).expect(200)).body.data.rows.find((row:{id:string})=>row.id===other.id).history;
        assert.equal(history[0].status,'Reversed');
        const second=(await post('/payments',{labourId:other.id,throughWeek:next,date:today(),amount:'600.00',mode:'UPI',requestId:randomUUID()}).expect(201)).body.data;
        const race=await Promise.all([post('/payments/'+second.id+'/reverse',{...undo,requestId:randomUUID()}),post('/payments/'+second.id+'/reverse',{...undo,requestId:randomUUID()})]);
        assert.deepEqual(race.map(result=>result.status).sort(),[201,409]);
        assert.equal(await Reversal.countDocuments({kind:'Payment'}),2);assert.equal(await Audit.countDocuments({action:'PAYMENT_REVERSED'}),2);
        const paymentsCSV=(await get('/reports/payments.csv').expect(200)).text;
        assert.match(paymentsCSV,/"-1500.00"/);assert.ok(!paymentsCSV.includes("'-1500.00"));
        const costCSV=(await get('/reports/labour-cost.csv').expect(200)).text;
        assert.match(costCSV,/Wage correction/);assert.ok(!costCSV.includes('ADVANCE_REFUND'));
        assert.match((await get('/reports/corrections.csv').expect(200)).text,/ADVANCE_REFUND/);
        assert.match((await get('/reports/advances.csv').expect(200)).text,/Reversed/);
        const multiRefund=await post('/advances/'+active+'/reverse',{...reversal,requestId:randomUUID()}).expect(201);
        assert.equal(multiRefund.body.data.refund,'1150.00');assert.equal(multiRefund.body.data.settlementWeek,shift(third,7));
        assert.equal(await Adjustment.countDocuments({sourceReversalId:multiRefund.body.data.id}),2);
        const refundOnly=(await get('/payroll?week='+shift(third,7)).expect(200)).body.data.rows.find((row:{id:string})=>row.id===worker.id);
        assert.equal(refundOnly.gross,'0.00');assert.equal(refundOnly.adjustment,'1150.00');assert.equal(refundOnly.advance,'0.00');assert.equal(refundOnly.net,'1150.00');
        await approve(shift(third,7)).expect(200);
    } finally {assert.equal(mongoose.connection.name,dbName);await mongoose.connection.dropDatabase();await mongoose.disconnect();}
});
